/**
 * 每篇笔记「看到哪儿、收起了哪几段」。
 *
 * # 为什么要单独一个文件
 *
 * 这两份记录必须活得比编辑器组件久:切标签是同一个组件换文档,但**离开笔记页**
 * (去设置、去智能体)整个组件会卸载重建。写在 `<script setup>` 里的变量是
 * setup 函数的局部变量 —— 每次挂载都是新的一份,记的东西全没了。
 * 放在模块作用域才是真正的「这个页面活着就一直在」。
 *
 * # 记行号,不记字符偏移
 *
 * 别处改了字数,偏移就全错位;行号在「切走再回来」这种场景里稳得多。
 * 对不上的(那一行已经不是标题了)恢复时直接丢掉。
 */

/** 笔记路径 → 滚动条位置 */
export const scrollMemory = new Map<string, number>()

/** 笔记路径 → 收起来的那些标题所在的行号 */
