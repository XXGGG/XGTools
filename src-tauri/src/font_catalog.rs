#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn catalog_is_consistent() {
        let mut ids = std::collections::HashSet::new();
        for p in CATALOG {
            assert!(ids.insert(p.id), "id 重复: {}", p.id);
            assert!(!p.uses.is_empty(), "{} 没放进任何用途", p.id);
            for u in p.uses {
                assert!(USES.contains(u), "{} 的用途 {u} 不在 USES 里", p.id);
            }
            assert!(p.url.starts_with("https://github.com/"), "{} 下载地址不在 GitHub", p.id);
            assert!(p.license_url.starts_with("https://"), "{} 缺协议原文", p.id);
            assert!(!p.families.is_empty(), "{} 没写族名", p.id);
        }
        // 每个用途小类都至少有一款
        for u in USES {
            assert!(CATALOG.iter().any(|p| p.uses.contains(u)), "用途 {u} 是空的");
        }
        let _ = GF;
    }
}
