//! 字体库「推荐」里的字体。
//!
//! 条目从 XGCut 那份核过协议原文的目录里挑出来，按我们的三种用途重新分组：
//! 做游戏、剪视频、PS 做图。一款字可以出现在好几个用途里（得意黑既是游戏标题也是视频封面）。
//!
//! 收录标准照旧：协议必须是开源协议（OFL 为主，霞鹜新晰黑是 IPA），
//! 而且能在项目仓库里点开协议原文。厂商「声明免费商用」但没有开源协议的不收。
//!
//! 下面几个字段不是手写的，是拿字体文件本身量出来的（scripts/make-font-previews.py
//! 用的也是同一批文件）：
//!
//! - `families`：装好之后系统里的英文族名。拿它认「本机已经装过了」
//! - `px`：像素字的原生字号。把几个字形的轮廓坐标求最大公约数就是一个「像素」多大，
//!   em 除以它就是网格对齐的字号 —— 只有在它的整数倍上才是清清楚楚的方块
//! - `sc` `tc` `kana` `latin`：cmap 里真的有简体 / 繁体 / 假名 / 西文

use serde::Serialize;

#[derive(Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Pack {
    pub id: &'static str,
    /// 中文名
    pub name: &'static str,
    /// 原名
    pub latin: &'static str,
    /// 一句话：长什么样、适合干嘛
    pub note: &'static str,
    /// 放在哪几个用途小类里，见 USES
    pub uses: &'static [&'static str],
    pub license: &'static str,
    /// 协议原文（点开能直接看条款）
    pub license_url: &'static str,
    pub home: &'static str,
    pub url: &'static str,
    /// 下载包大概多大（MB）
    pub size_mb: u32,
    pub families: &'static [&'static str],
    pub px: &'static [u16],
    pub sc: bool,
    pub tc: bool,
    pub kana: bool,
    pub latin_ok: bool,
    /// 压缩包里一套字给了好几种语言版本时，只装名字里带这个的那份；空 = 全装
    pub pick: &'static str,
}

